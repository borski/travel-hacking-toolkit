#!/usr/bin/env python3
"""
ViajaNet / Decolar (Despegar platform) cash flight search via Patchright.

ViajaNet and Decolar run on the same Despegar storefront. Their results page
calls /shop/flights-busquets/api/v1/web/search, but that request carries a
signature (`h=`) and session ids generated by the page's JavaScript, so it
can't be called directly. We load the public results URL in a real browser and
capture the search response the page fetches for itself.

Why bother: these Brazilian OTAs list carriers and fares the global sources
miss (Arajet, Brazilian LCC combos, BRL-only promos) and report the exact
baggage included in each fare.

Usage:
    python3 search_viajanet.py --origin GRU --dest YYZ \
        --depart 2027-10-01 --return 2027-10-16 --json

    # Same search on decolar.com
    python3 search_viajanet.py --site decolar --origin GRU --dest YYZ \
        --depart 2027-10-01 --return 2027-10-16 --json

Exit codes:
    0  results found (or empty result set with no error)
    1  blocked / no search response captured
    2  bad arguments
"""

import argparse
import json
import os
import re
import sys
import tempfile
import time
from pathlib import Path


SITES = {
    "viajanet": "https://www.viajanet.com.br",
    "decolar": "https://www.decolar.com",
}
API_PATH = "/shop/flights-busquets/api/v1/web/search"

BLOCK_MARKERS = (
    "Access Denied",
    "Too Many Requests",
    "verify you are human",
    "Pardon Our Interruption",
)

# clusterType values meaning the trip is sold as separate tickets.
SEPARATE_TICKET_CLUSTERS = ("VIRTUAL_INTERLINING", "2OW")


def in_docker():
    return Path("/.dockerenv").exists() or os.environ.get("VIAJANET_IN_DOCKER") == "1"


def get_profile_dir():
    if in_docker():
        return tempfile.mkdtemp(prefix="viajanet-")
    env_dir = os.environ.get("VIAJANET_PROFILE")
    if env_dir:
        return env_dir
    return str(Path.home() / ".viajanet-profiles" / "default")


def validate_iata(code):
    code = (code or "").strip().upper()
    if not re.fullmatch(r"[A-Z]{3}", code):
        raise ValueError(f"invalid IATA code: {code!r}")
    return code


def validate_date(value):
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", value or ""):
        raise ValueError(f"invalid date (expected YYYY-MM-DD): {value!r}")
    return value


def build_results_url(site, origin, dest, depart, ret=None, adults=1, children=0, infants=0):
    base = SITES[site]
    if ret:
        return (f"{base}/shop/flights/results/roundtrip/{origin}/{dest}/"
                f"{depart}/{ret}/{adults}/{children}/{infants}")
    return f"{base}/shop/flights/results/oneway/{origin}/{dest}/{depart}/{adults}/{children}/{infants}"


def text_has_block_marker(text):
    if not text:
        return False
    low = text.lower()
    return any(marker.lower() in low for marker in BLOCK_MARKERS)


def _hhmm(iso):
    """'2027-10-01T23:55:00-03:00' -> '2027-10-01 23:55'."""
    if not iso:
        return None
    return iso[:16].replace("T", " ")


def _bags(info):
    info = info or {}
    return {
        "checked": info.get("quantity", 0),
        "carryOn": info.get("carryonType") == "INCLUDED",
        "personalItem": info.get("backpackType") == "INCLUDED",
        "checkedPurchasable": "UPSELL" in (info.get("baggageInfoType") or ""),
    }


def _route(choice):
    routes = choice.get("routes") or []
    if not routes:
        return None
    idx = (choice.get("selectedRouteIndex") or 1) - 1
    route = routes[idx] if 0 <= idx < len(routes) else routes[0]
    return {
        "departure": _hhmm((route.get("departure") or {}).get("date")),
        "arrival": _hhmm((route.get("arrival") or {}).get("date")),
        "duration": route.get("totalDuration"),
        "stops": route.get("stopsCount"),
        "airlines": route.get("airlines") or [],
        "via": [s["arrival"]["airportCode"] for s in (route.get("segments") or [])[:-1]
                if (s.get("arrival") or {}).get("airportCode")],
        "flights": [s.get("flightId") for s in route.get("segments") or []],
        "bags": _bags(route.get("baggageInfo")),
    }


def parse_search(payload):
    """Flatten a busquets /search response into one row per itinerary. Pure."""
    rows = []
    for wrapper in (payload or {}).get("items") or []:
        item = wrapper.get("item") or {}
        price = item.get("priceDetail") or {}
        total = (price.get("mainFare") or {}).get("amount")
        if total is None:
            continue
        breakdown = {i.get("type"): i.get("amount") for i in price.get("items") or []}
        legs = {}
        for choice in item.get("routeChoices") or []:
            legs[(choice.get("type") or "").lower()] = _route(choice)
        cluster = item.get("clusterType") or ""
        rows.append({
            "totalBRL": total,
            "fareBRL": breakdown.get("ADULTS"),
            "taxesBRL": breakdown.get("TAXES_AND_CHARGES"),
            "currency": price.get("currencyCode"),
            "validatingCarrier": item.get("validatingCarrier"),
            "airlines": item.get("airlines") or [],
            "separateTickets": any(k in cluster for k in SEPARATE_TICKET_CLUSTERS),
            "clusterType": cluster or None,
            "outbound": legs.get("outbound"),
            "inbound": legs.get("inbound"),
        })
    rows.sort(key=lambda r: r["totalBRL"])
    return rows


def search(args):
    profile_dir = get_profile_dir()
    os.makedirs(profile_dir, exist_ok=True)

    from patchright.sync_api import sync_playwright

    url = build_results_url(args.site, args.origin, args.dest, args.depart, args.ret,
                            args.adults, args.children, args.infants)
    payloads = []

    def on_response(resp):
        if API_PATH in resp.url:
            try:
                payloads.append(resp.json())
            except Exception:
                pass

    with sync_playwright() as p:
        launch = dict(
            user_data_dir=profile_dir,
            headless=False,
            viewport={"width": 1400, "height": 900},
            locale="pt-BR",
        )
        try:
            ctx = p.chromium.launch_persistent_context(
                channel="chrome" if not in_docker() else None, **launch
            )
        except Exception:
            ctx = p.chromium.launch_persistent_context(**launch)

        page = ctx.pages[0] if ctx.pages else ctx.new_page()
        page.on("response", on_response)

        for attempt in range(1, args.retries + 1):
            try:
                page.goto(url, wait_until="domcontentloaded", timeout=60000)
                deadline = time.time() + 40
                while not any((pl or {}).get("items") for pl in payloads) and time.time() < deadline:
                    time.sleep(1)
                if any((pl or {}).get("items") for pl in payloads):
                    break
                body = page.evaluate("() => document.body ? document.body.innerText.slice(0, 400) : ''")
                reason = "block/challenge page" if text_has_block_marker(body) else "no search response"
                print(f"[attempt {attempt}] {reason}, retrying…", file=sys.stderr)
                payloads.clear()
                time.sleep(4 * attempt)
            except Exception as e:
                print(f"[attempt {attempt}] navigation error: {e}", file=sys.stderr)
                time.sleep(3 * attempt)

        final_url = page.url
        ctx.close()

    rows = []
    for pl in payloads:
        rows.extend(parse_search(pl))
    if not rows and not payloads:
        print(f"ERROR: no search response captured from {args.site}. Retry later "
              "from a residential connection.", file=sys.stderr)
        sys.exit(1)
    rows.sort(key=lambda r: r["totalBRL"])
    if args.limit:
        rows = rows[: args.limit]

    return {
        "source": args.site,
        "searchUrl": final_url,
        "query": {
            "origin": args.origin, "destination": args.dest,
            "depart": args.depart, "return": args.ret,
            "adults": args.adults, "children": args.children, "infants": args.infants,
        },
        "count": len(rows),
        "itineraries": rows,
    }


def parse_args(argv=None):
    ap = argparse.ArgumentParser(description="ViajaNet / Decolar flight search via Patchright")
    ap.add_argument("--site", default="viajanet", choices=sorted(SITES))
    ap.add_argument("--origin", required=True, help="Origin IATA, e.g. GRU")
    ap.add_argument("--dest", required=True, help="Destination IATA, e.g. YYZ")
    ap.add_argument("--depart", required=True, help="Departure date YYYY-MM-DD")
    ap.add_argument("--return", dest="ret", help="Return date YYYY-MM-DD (omit for one-way)")
    ap.add_argument("--adults", type=int, default=1)
    ap.add_argument("--children", type=int, default=0)
    ap.add_argument("--infants", type=int, default=0)
    ap.add_argument("--limit", type=int, default=20)
    ap.add_argument("--retries", type=int, default=3)
    ap.add_argument("--json", action="store_true", help="Emit JSON to stdout")
    args = ap.parse_args(argv)
    try:
        args.origin = validate_iata(args.origin)
        args.dest = validate_iata(args.dest)
        args.depart = validate_date(args.depart)
        if args.ret:
            args.ret = validate_date(args.ret)
    except ValueError as e:
        ap.print_usage(sys.stderr)
        print(f"error: {e}", file=sys.stderr)
        sys.exit(2)
    return args


def main():
    args = parse_args()
    result = search(args)

    if args.json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
        return

    print(f"{args.site} — {result['count']} itineraries", file=sys.stderr)
    print(f"  {result['searchUrl']}\n", file=sys.stderr)
    for r in result["itineraries"]:
        flag = "  [bilhetes separados]" if r["separateTickets"] else ""
        print(f"• R$ {r['totalBRL']:,.0f}  {'/'.join(r['airlines'])}{flag}")
        for name in ("outbound", "inbound"):
            leg = r.get(name)
            if not leg:
                continue
            via = f" via {','.join(leg['via'])}" if leg["via"] else ""
            bags = leg["bags"]
            print(f"    {name}: {leg['departure']} → {leg['arrival']} ({leg['duration']}, "
                  f"{leg['stops']} parada(s){via}) mala desp.: {bags['checked']}")


if __name__ == "__main__":
    main()
